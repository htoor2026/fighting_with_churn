-- Instead of calculating the 28-day "like" count for one measurement date,
it calculates that same metric repeatedly across many weekly measurement dates


WITH date_vals AS (
    SELECT i::timestamp AS metric_date
    FROM generate_series(
        '2020-01-29'::timestamp,
        '2020-04-16'::timestamp,
        '7 day'::interval
    ) AS i
)

SELECT
    e.account_id,
    d.metric_date,
    COUNT(*) AS n_like_per_month

FROM socialnet7.event e

INNER JOIN date_vals d
    ON e.event_time < d.metric_date
    AND e.event_time >= d.metric_date - INTERVAL '28 day'

INNER JOIN socialnet7.event_type t
    ON t.event_type_id = e.event_type_id

WHERE t.event_type_name = 'like'

GROUP BY
    e.account_id,
    d.metric_date

ORDER BY
    e.account_id,
    d.metric_date;

