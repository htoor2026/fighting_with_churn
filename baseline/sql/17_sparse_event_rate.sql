-- his query is converting an 84-day unfriend count into an equivalent 28-day average rate.

-- The core is:

-- (28.0 / 84.0) * COUNT(*)

-- Since:

-- $$ \frac{28}{84}=\frac13 $$

-- you are basically doing:

-- $$ \text{28-day average unfriend count} = \frac{\text{unfriend events in last 84 days}}{3} $$

-- So:

-- 1 unfriend in 84 days  → 0.33 per 28 days
-- 2                    → 0.67
-- 3                    → 1.00
-- 5                    → 1.67

-- Why do this? Because unfriend is a rare event. A normal 28-day window may contain too many zeros, so using a longer 84-day window gives a more stable signal, then you scale it back to a 28-day comparable rate.

-- That is a useful feature-engineering idea:

-- For sparse behaviors, use a longer observation window to reduce noise, then normalize to the desired time scale.

-- So this is effectively an 84-day smoothed unfriend rate expressed on a 28-day basis.

WITH date_vals AS (
    SELECT
        i::timestamp AS metric_date
    FROM generate_series(
        '2020-05-10'::timestamp,
        '2020-05-10'::timestamp,
        '7 day'::interval
    ) AS i
)

SELECT
    e.account_id,
    d.metric_date,
    COUNT(*) AS total_count,
    (28.0 / 84.0) * COUNT(*) AS n

FROM socialnet7.event e

INNER JOIN date_vals d
    ON e.event_time <= d.metric_date
    AND e.event_time > d.metric_date - INTERVAL '84 day'

INNER JOIN socialnet7.event_type t
    ON t.event_type_id = e.event_type_id

WHERE
    t.event_type_name = 'unfriend'

GROUP BY
    e.account_id,
    d.metric_date

ORDER BY
    e.account_id,
    d.metric_date;

