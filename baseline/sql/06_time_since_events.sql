WITH date_vals AS (
    SELECT
        i::date AS metric_date
    FROM generate_series(
        '2020-05-03'::date,
        '2020-05-10'::date,
        '7 day'::interval
    ) AS i
),

last_event AS (
    SELECT
        e.account_id,
        d.metric_date,
        MAX(e.event_time)::date AS last_date
    FROM socialnet7.event e

    INNER JOIN date_vals d
        ON e.event_time::date <= d.metric_date

    INNER JOIN socialnet7.event_type t
        ON t.event_type_id = e.event_type_id

    WHERE
        t.event_type_name = 'like'

    GROUP BY
        e.account_id,
        d.metric_date
)

SELECT
    account_id,
    metric_date,
    last_date,
    metric_date - last_date AS days_since_event

FROM last_event

ORDER BY
    account_id,
    metric_date;

